// Class weapons as 64x64 rig cells (the art the hero generator put in the weapon slots): the
// SDK paints them into weapons/weapon1, shields into weapons/offhand1, and bows into weapons/bow.
{
  const weaponSrc = path.join(SRC, 'assets/images/hero/weapons')
  fs.mkdirSync(path.join(ROOT, 'assets/hero-rig/weapons'), { recursive: true })
  const cells = {}
  for (const file of fs.readdirSync(weaponSrc).filter(f => f.endsWith('.png')).sort()) {
    const buf = fs.readFileSync(path.join(weaponSrc, file))
    // PNG IHDR: width and height are big-endian at bytes 16 and 20.
    if (buf.readUInt32BE(16) !== 64 || buf.readUInt32BE(20) !== 64) continue
    fs.copyFileSync(path.join(weaponSrc, file), path.join(ROOT, 'assets/hero-rig/weapons', file))
    const [, name, kind] = file.match(/^(\w+)-(weapon|shield|wand|bow)\.png$/) ?? []
    if (!name) continue
    const slot = kind === 'shield' ? 'shield' : kind === 'bow' ? 'bow' : 'weapon'
    ;(cells[name] ??= {})[slot] = `weapons/${file}`
  }
  writeRigWeapons(cells)
}

// Equipped weapons and shields as 64x64 rig cells, plus the rules the game uses to show them
// (read from its own code: the item -> art table in getWeaponAndPositionByClass, which weapon
// types are two-handed, and which animation set each weapon type plays in combat).
{
  const heroUtils = fs.readFileSync(path.join(SRC, 'features/heroes/utils/index.ts'), 'utf8')
  const equipTypes = fs.readFileSync(path.join(SRC, 'features/combat/shared/equipment/types.ts'), 'utf8')
  const equipUtils = fs.readFileSync(path.join(SRC, 'features/equipment/utils/index.ts'), 'utf8')

  // enum WeaponTypes { UNCATEGORIZED, ONE_H_AXE = 1, TWO_H_AXE, … } -> name -> number
  const weaponTypes = {}
  {
    const body = equipTypes.match(/export enum WeaponTypes \{([\s\S]*?)\}/)?.[1]
    if (!body) throw new Error('could not find enum WeaponTypes')
    let next = 0
    for (const m of body.matchAll(/(\w+)\s*(?:=\s*(\d+))?\s*,?/g)) {
      if (m[2] !== undefined) next = Number(m[2])
      weaponTypes[m[1]] = next++
    }
  }
  const typeId = name => {
    if (weaponTypes[name] === undefined) throw new Error(`unknown WeaponTypes.${name}`)
    return weaponTypes[name]
  }

  const fn = heroUtils.match(/export function getWeaponAndPositionByClass[\s\S]*?\n\}\n/)?.[0]
  if (!fn) throw new Error('could not find getWeaponAndPositionByClass')
  const weapons = {}
  const offhands = {}
  let currentType
  let currentId
  let offhandId
  for (const line of fn.split('\n')) {
    const type = line.match(/weaponType === WeaponTypes\.(\w+)\)/)
    if (type) currentType = typeId(type[1])
    const id = line.match(/weaponDisplayId === (\d+)/)
    if (id) currentId = Number(id[1])
    const off = line.match(/offhand1_display_id === (\d+)/)
    if (off) offhandId = Number(off[1])
    const art = line.match(/(offhandImagePath|imagePath) = `\$\{globalPath\}\/equippable\/([^`]+)`/)
    if (!art) continue
    if (art[1] === 'offhandImagePath') offhands[offhandId] = art[2]
    else (weapons[currentType] ??= {})[currentId] = art[2]
  }
  // The block that hides the offhand lists the two-handed weapon types.
  const hideOffhand = fn.match(/if \(\s*(hero\.equipment\.weapon1_weapon_type === WeaponTypes\.\w+[\s\S]*?)\)\s*\{\s*offhandImagePath = empty/)
  if (!hideOffhand) throw new Error('could not find the two-handed weapon check')
  const twoHanded = [...hideOffhand[1].matchAll(/WeaponTypes\.(\w+)/g)].map(m => typeId(m[1]))

  // getWeaponStringByType + enum WeaponTypeStrings -> the animation set each type plays.
  const strings = Object.fromEntries(
    [...(equipTypes.match(/export enum WeaponTypeStrings \{([\s\S]*?)\}/)?.[1] ?? '').matchAll(/(\w+)\s*=\s*'([^']+)'/g)].map(m => [m[1], m[2]])
  )
  const switchBody = equipUtils.match(/export function getWeaponStringByType[\s\S]*?\n\}/)?.[0]
  if (!switchBody || !Object.keys(strings).length) throw new Error('could not find getWeaponStringByType / WeaponTypeStrings')
  const animationSets = {}
  for (const m of switchBody.matchAll(/case WeaponTypes\.(\w+):\s*return WeaponTypeStrings\.(\w+)/g)) animationSets[typeId(m[1])] = strings[m[2]]

  const artSrc = path.join(IFACE, 'public/assets/weapons/equippable')
  const artOut = path.join(ROOT, 'assets/hero-rig/weapons/equippable')
  fs.rmSync(artOut, { recursive: true, force: true })
  // Drop entries whose art the client doesn't actually ship (heroes fall back to class weapons).
  const exists = file => {
    if (fs.existsSync(path.join(artSrc, file))) return true
    console.warn(`  skipping equippable/${file}: referenced by the client but missing`)
    return false
  }
  for (const byId of Object.values(weapons)) for (const [id, file] of Object.entries(byId)) if (!exists(file)) delete byId[id]
  for (const [id, file] of Object.entries(offhands)) if (!exists(file)) delete offhands[id]
  const files = [...Object.values(weapons).flatMap(Object.values), ...Object.values(offhands)]
  for (const file of files) {
    const buf = fs.readFileSync(path.join(artSrc, file))
    if (buf.readUInt32BE(16) !== 64 || buf.readUInt32BE(20) !== 64) throw new Error(`${file} isn't a 64x64 rig cell`)
    fs.mkdirSync(path.dirname(path.join(artOut, file)), { recursive: true })
    fs.copyFileSync(path.join(artSrc, file), path.join(artOut, file))
  }
  const prefix = obj => Object.fromEntries(Object.entries(obj).map(([k, v]) => [k, `weapons/equippable/${v}`]))
  const table = {
    weapons: Object.fromEntries(Object.entries(weapons).map(([t, byId]) => [t, prefix(byId)])),
    offhands: prefix(offhands),
    twoHanded,
    animationSets,
  }
  write(
    'rig-equipment.ts',
    `/**
 * Equipped gear as hero rig cells, from the game client: weapon type id -> display id -> cell,
 * offhand display id -> cell, the weapon types that hide the offhand, and the animation set each
 * weapon type plays.
 */
export const RIG_EQUIPMENT: {
  weapons: Record<string, Record<string, string>>
  offhands: Record<string, string>
  twoHanded: number[]
  animationSets: Record<string, string>
} = ${JSON.stringify(table, null, 1)}\n`
  )
  console.log(`  ${files.length} equipped weapon/shield cells`)
}

function writeRigWeapons(cells) {
  write('rig-weapons.ts', `/** Class weapon cells for the hero rig, keyed by lower-cased class. */\nexport const RIG_WEAPONS: Record<string, { weapon?: string; shield?: string; bow?: string }> = ${JSON.stringify(cells, null, 1)}\n`)
}

function namesSafeGrabGold() {
  const src = fs.readFileSync(path.join(SRC, 'constants/index.ts'), 'utf8')
  const block = src.match(/export const GOLD_ADDRESSES[^{]*\{([\s\S]*?)\n\}/)
  if (!block) throw new Error('could not find GOLD_ADDRESSES')
  const chainIds = readChainIds()
  const out = {}
  for (const m of block[1].matchAll(/\[ChainId\.(\w+)\]:\s*'(0x[0-9a-fA-F]{40})'/g)) out[chainIds[m[1]]] = m[2]
  return out
}

function readChainIds() {
  const src = fs.readFileSync(path.join(SRC, 'constants/sdk-extra/constants.ts'), 'utf8')
  const block = src.match(/export enum ChainId \{([\s\S]*?)\}/)[1]
  return Object.fromEntries([...block.matchAll(/(\w+)\s*=\s*(\d+)/g)].map(m => [m[1], Number(m[2])]))
}
