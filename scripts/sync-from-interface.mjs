  // Description functions interpolate expressions of the raw scalar: `scalar / divisor`, or for
  // ranges `scalar % 256` and `floor(scalar / 256)`. Render once with NaN to find the
  // placeholders, then once with a probe scalar to tell which expression each one is.
  const PROBE = 0x0503 // low byte 3, high byte 5, and an unambiguous value when divided
  const templates = (fn, ids) => {
    const out = {}
    for (const id of ids) {
      const raw = fn(id, NaN)
      if (typeof raw !== 'string') continue
      const pieces = stripHtml(raw).split('NaN')
      const probe = stripHtml(fn(id, PROBE))
      let pos = pieces[0].length
      let divisor
      const tokens = []
      for (let i = 1; i < pieces.length; i++) {
        const end = pieces[i] ? probe.indexOf(pieces[i], pos) : probe.length
        const shown = parseFloat(probe.slice(pos, end))
        if (shown === (PROBE % 256)) tokens.push('{low}')
        else if (shown === Math.floor(PROBE / 256)) tokens.push('{high}')
        else {
          tokens.push('{value}')
          divisor = shown ? PROBE / shown : 1
        }
        pos = end + pieces[i].length
      }
      const template = pieces.reduce((acc, piece, i) => acc + (i ? tokens[i - 1] : '') + piece, '')
      out[id] = divisor && divisor !== 1 ? { template, divisor: Math.round(divisor * 1e6) / 1e6 } : { template }
    }
    return out
  }
