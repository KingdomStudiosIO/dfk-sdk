function addressesFromConstants(name) {
  const m = constantsSrc.match(new RegExp(`export const ${name}\\b[^=]*=\\s*\\{([\\s\\S]*?)\\n\\}`))
  if (!m) return undefined
  const out = {}
  // Matches both `[ChainId.X]: '0x…'` and `new Token(ChainId.X, '0x…', …)`.
  for (const a of m[1].matchAll(/ChainId\.(\w+)\]?\s*[:,]\s*'(0x[0-9a-fA-F]{40})'/g)) {
    const id = chainIds[a[1]]
    if (id !== undefined && !PLACEHOLDER_ADDRESS.test(a[2])) out[id] = a[2]
  }
  return Object.keys(out).length ? out : undefined
}
