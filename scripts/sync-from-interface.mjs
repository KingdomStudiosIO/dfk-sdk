  // The markup is flat and regular: part <div>s holding <img> and <svg><path/></svg> layers.
  function parseParts(html) {
    const parts = []
    const stack = []
    const tagRe = /<(\/?)(div|img|svg|path)\b([^>]*?)(\/?)>/g
    const attrs = s => Object.fromEntries([...s.matchAll(/([\w:-]+)="([^"]*)"/g)].map(x => [x[1], x[2]]))
    let svg = null
    for (const t of html.matchAll(tagRe)) {
      const [, close, tag, rawAttrs, selfClose] = t
      const a = attrs(rawAttrs)
      if (tag === 'div') {
        if (close) stack.pop()
        else {
          const part = { part: (a.class ?? '').split(' ')[0], layers: [] }
          stack.push(part)
          parts.push(part)
        }
        continue
      }
      const part = stack[stack.length - 1]
      if (!part) continue
      const role = (a.class ?? '').split(' ')[0]
      if (tag === 'img') {
        // Only the SVG layer art is shipped; a few class weapons are PNGs outside the hero art set.
        if (a.src && a.src.endsWith('.svg') && !a.src.startsWith('..')) {
          usedFiles.add(a.src)
          part.layers.push({ role: role === 'heroUndies' ? 'undies' : role, src: a.src })
        }
      } else if (tag === 'svg' && !close) {
        const color = COLORS[(a.stroke ?? '').replace('#', '')]
        if (a['data-src']) {
          usedFiles.add(a['data-src'])
          part.layers.push({ role: 'color', src: a['data-src'], ...(color ? { color } : {}) })
        } else {
          const [, , w, h] = (a.viewBox ?? '0 0 30 45').split(/\s+/).map(Number)
          svg = { role: 'color', viewBox: [w, h], paths: [] }
          part.layers.push(svg)
        }
        if (selfClose) svg = null
      } else if (tag === 'svg' && close) {
        svg = null
      } else if (tag === 'path' && svg && !close) {
        const color = COLORS[(a.stroke ?? '').replace('#', '')]
        if (a.d) svg.paths.push({ d: a.d, ...(color ? { color } : { stroke: a.stroke }) })
      }
    }
    // Drop empty wrappers (arm groups) and inline color layers with nothing to draw.
    for (const p of parts) p.layers = p.layers.filter(l => !l.paths || l.paths.length)
    return parts.filter(p => p.layers.length)
  }

  const classBlock = fs.readFileSync(path.join(ROOT, 'src/heroes/constants.ts'), 'utf8').match(/HERO_CLASSES = \{([\s\S]*?)\}/)[1]
